# Terminal system: PowerShell and Git Bash in one window, same directory.
#
# Two layers:
#   Enter-ZetaShell      in-place handoff, works in any terminal. The trick is the return trip:
#                        a child cannot change its parent's cwd, so the generated bash rcfile
#                        records $PWD on EXIT and PowerShell adopts it afterwards.
#   Open-ZetaShellTab    a peer Windows Terminal tab at the same directory (Ctrl+Tab to jump).

$script:ZetaBashPathCache = $null

function Get-ZetaBashPath {
    <#
    .SYNOPSIS
        Locate Git Bash, never the WSL launcher that masquerades as bash.exe in System32.
    #>    param([switch]$Refresh)

    if ($env:ZETA_BASH_PATH) { return $env:ZETA_BASH_PATH }
    if ($script:ZetaBashPathCache -and -not $Refresh) { return $script:ZetaBashPathCache }

    $candidates = @()
    if ($env:ProgramFiles) { $candidates += (Join-Path $env:ProgramFiles 'Git\bin\bash.exe') }
    $x86 = ${env:ProgramFiles(x86)}
    if ($x86) { $candidates += (Join-Path $x86 'Git\bin\bash.exe') }
    if ($env:LOCALAPPDATA) { $candidates += (Join-Path $env:LOCALAPPDATA 'Programs\Git\bin\bash.exe') }

    foreach ($candidate in $candidates) {
        if ($candidate -and (Test-Path -LiteralPath $candidate)) {
            $script:ZetaBashPathCache = $candidate
            return $candidate
        }
    }

    $command = Get-Command -Name 'bash' -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1
    if ($command -and $command.Source -and $command.Source -notmatch '\\Windows\\System32\\') {
        $script:ZetaBashPathCache = $command.Source
        return $command.Source
    }
    return $null
}

function ConvertTo-ZetaPosixPath {
    <#
    .SYNOPSIS
        C:\Users\me -> /c/Users/me, for handing paths to Git Bash.
    #>
    param([Parameter(Mandatory)][string]$Path)

    $normalised = $Path -replace '\\', '/'
    if ($normalised -match '^([A-Za-z]):(.*)$') {
        return ('/' + $Matches[1].ToLowerInvariant() + $Matches[2])
    }
    return $normalised
}

function ConvertFrom-ZetaPosixPath {
    <#
    .SYNOPSIS
        /c/Users/me -> C:\Users\me (and //server/share -> \\server\share).
    #>
    param([Parameter(Mandatory)][string]$Path)

    $trimmed = $Path.Trim()
    if ($trimmed -match '^/([A-Za-z])(/.*)?$') {
        return ($Matches[1].ToUpperInvariant() + ':' + ($Matches[2] -replace '/', '\'))
    }
    if ($trimmed -match '^//([^/]+)/(.*)$') {
        return ('\\' + $Matches[1] + '\' + ($Matches[2] -replace '/', '\'))
    }
    return $trimmed
}

function New-ZetaBashRcFile {
    <#
    .SYNOPSIS
        Generate the throwaway rcfile: user startup files first, then Zeta's bash runtime.
    #>
    param(
        [Parameter(Mandatory)][string]$TokenPosix,
        [hashtable]$Environment = @{},
        [string]$RuntimePosix
    )

    $directory = Join-Path ([System.IO.Path]::GetTempPath()) ('zeta-bash-' + [Guid]::NewGuid().ToString('N').Substring(0, 8))
    New-Item -ItemType Directory -Path $directory -Force | Out-Null
    $rcFile = Join-Path $directory 'zeta-bashrc.sh'

    $safeToken = $TokenPosix -replace '"', ''
    $lines = @(
        '# generated by Zeta for one interactive session - safe to delete'
        '[ -f /etc/profile ] && . /etc/profile'
        '[ -f ~/.bash_profile ] && . ~/.bash_profile'
        '[ -f ~/.bashrc ] && . ~/.bashrc'
        ('__zeta_cwd_file="{0}"' -f $safeToken)
        '__zeta_dump_cwd() { [ -n "$__zeta_cwd_file" ] && pwd -P >| "$__zeta_cwd_file" 2>/dev/null; }'
        '__zeta_dump_cwd'
        'trap __zeta_dump_cwd EXIT'
    )

    if ($Environment -and $Environment.Count -gt 0) {
        $lines += ''
        foreach ($key in ($Environment.Keys | Sort-Object)) {
            $value = $Environment[$key]
            if ($null -eq $value -or "$value" -eq '') { continue }
            $lines += ('export {0}={1}' -f $key, (ConvertTo-ZetaBashSingleQuoted ([string]$value)))
        }
    }

    if ($RuntimePosix) {
        $lines += ''
        $lines += ('[ -f {0} ] && . {0}' -f (ConvertTo-ZetaBashSingleQuoted $RuntimePosix))
    }

    Set-Content -LiteralPath $rcFile -Value ($lines -join "`n") -Encoding ASCII
    return $rcFile
}

function Get-ZetaBashEnvironment {
    <#
    .SYNOPSIS
        Environment a bash session needs to run Zeta's runtime.
    #>
    param([string]$ThemePath)

    $themeFile = $ThemePath
    if (-not $themeFile) { $themeFile = Get-ZetaBashThemePath }
    $runtime = Join-Path (Join-Path $script:ModuleRoot 'Shell') 'zeta.bash'
    $shellHost = Get-Command -Name 'pwsh' -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1
    $shellHostPath = 'powershell.exe'
    if ($shellHost) { $shellHostPath = $shellHost.Source }

    $environment = @{
        ZETA_VERSION    = $script:ZetaVersion
        ZETA_THEME_FILE = ConvertTo-ZetaPosixPath -Path $themeFile
        ZETA_RUNTIME    = ConvertTo-ZetaPosixPath -Path $runtime
        ZETA_MANIFEST   = (Join-Path $script:ModuleRoot 'Zeta.psd1')
        ZETA_THEMES_DIR = ConvertTo-ZetaPosixPath -Path (Join-Path $script:ModuleRoot 'Themes')
        ZETA_POWERSHELL = $shellHostPath
    }
    $core = Get-ZetaCorePath
    if ($core) { $environment['ZETA_CORE'] = ConvertTo-ZetaPosixPath -Path $core }
    return $environment
}

function Install-ZetaBashProfile {
    <#
    .SYNOPSIS
        Give every Git Bash session the Zeta prompt and `zeta` command.

    .DESCRIPTION
        Writes a marker-delimited block to ~/.bashrc. Interactive-only, idempotent, and it
        never touches the user's own lines. Without this, only `zeta shell bash` is themed.

    .EXAMPLE
        Install-ZetaBashProfile

    .EXAMPLE
        Install-ZetaBashProfile -WhatIf
    #>
    [CmdletBinding(SupportsShouldProcess)]
    param([string]$Path)

    $homeDir = [Environment]::GetFolderPath('UserProfile')
    if (-not $Path) { $Path = Join-Path $homeDir '.bashrc' }

    $environment = Get-ZetaBashEnvironment
    $lines = @('# >>> zeta initialize >>>', 'case $- in *i*) ;; *) return ;; esac')
    foreach ($key in ($environment.Keys | Sort-Object)) {
        $lines += ('export {0}={1}' -f $key, (ConvertTo-ZetaBashSingleQuoted ([string]$environment[$key])))
    }
    $lines += '[ -f "$ZETA_RUNTIME" ] && . "$ZETA_RUNTIME"'
    $lines += '# <<< zeta initialize <<<'
    $block = $lines -join "`n"

    if (-not $PSCmdlet.ShouldProcess($Path, 'install Zeta bash hook')) { return $Path }

    $existing = ''
    if (Test-Path -LiteralPath $Path) { $existing = Get-Content -LiteralPath $Path -Raw }
    $pattern = '(?ms)^# >>> zeta initialize >>>.*?^# <<< zeta initialize <<<\s*'
    $cleaned = [regex]::Replace($existing, $pattern, '')
    $updated = ($cleaned.TrimEnd() + "`n`n" + $block + "`n")
    if ($updated.StartsWith("`n")) { $updated = $updated.Substring(1) }

    Set-Content -LiteralPath $Path -Value $updated -Encoding ASCII
    return $Path
}

function Get-ZetaShell {
    <#
    .SYNOPSIS
        Inventory of shells Zeta can hand off to.

    .EXAMPLE
        Get-ZetaShell
    #>
    [CmdletBinding()]
    param()

    $results = @()

    $pwsh = Get-Command -Name 'pwsh' -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1
    $results += [pscustomobject]@{
        Name      = 'pwsh'
        Kind      = 'PowerShell 7+'
        Path      = $(if ($pwsh) { $pwsh.Source } else { '' })
        Available = [bool]$pwsh
    }

    $winPs = Get-Command -Name 'powershell' -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1
    $results += [pscustomobject]@{
        Name      = 'powershell'
        Kind      = 'Windows PowerShell'
        Path      = $(if ($winPs) { $winPs.Source } else { '' })
        Available = [bool]$winPs
    }

    $bash = Get-ZetaBashPath
    $results += [pscustomobject]@{
        Name      = 'bash'
        Kind      = 'Git Bash'
        Path      = $(if ($bash) { $bash } else { '' })
        Available = [bool]$bash
    }

    $wsl = Get-Command -Name 'wsl' -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1
    $results += [pscustomobject]@{
        Name      = 'wsl'
        Kind      = 'WSL (no cwd handoff)'
        Path      = $(if ($wsl) { $wsl.Source } else { '' })
        Available = [bool]$wsl
    }

    return $results
}

function Enter-ZetaShell {
    <#
    .SYNOPSIS
        Enter another shell in the current directory; on exit, adopt the directory it ended in.

    .DESCRIPTION
        bash: launches Git Bash with a generated rcfile that records its final $PWD, so you come
        back to PowerShell in the directory you actually ended up in - not the one you left.

        pwsh / powershell: nested shell in the same directory. A child process cannot change its
        parent's directory, so the return trip keeps the original location; use `zeta shell tab`
        if you need two independent sessions.

    .EXAMPLE
        zeta shell bash

    .EXAMPLE
        Enter-ZetaShell -Name bash
    #>
    [CmdletBinding()]
    param(
        [Parameter(Position = 0)]
        [ValidateSet('bash', 'pwsh', 'powershell')]
        [string]$Name = 'bash'
    )

    switch ($Name) {
        'bash' {
            $bash = Get-ZetaBashPath
            if (-not $bash -or -not (Test-Path -LiteralPath $bash)) {
                $detail = ''
                if ($bash) { $detail = " at '$bash'" }
                throw ("Zeta: Git Bash not found{0}. Install it with: winget install --id Git.Git" -f $detail)
            }

            $cwdFile = Join-Path ([System.IO.Path]::GetTempPath()) ('zeta-cwd-' + [Guid]::NewGuid().ToString('N').Substring(0, 8) + '.txt')
            $previous = $env:ZETA_BASH_CWD_FILE
            $env:ZETA_BASH_CWD_FILE = ConvertTo-ZetaPosixPath -Path $cwdFile

            # Make sure the bash half of the theme exists before bash reads it.
            $themeFile = Join-Path (Join-Path ([Environment]::GetFolderPath('UserProfile')) '.zeta') 'theme.bash'
            if (-not (Test-Path -LiteralPath $themeFile)) {
                try { [void](Export-ZetaBashTheme) } catch { }
            }

            $runtime = Join-Path (Join-Path $script:ModuleRoot 'Shell') 'zeta.bash'
            $environment = Get-ZetaBashEnvironment -ThemePath $themeFile

            $rcFile = New-ZetaBashRcFile -TokenPosix $env:ZETA_BASH_CWD_FILE -Environment $environment -RuntimePosix $environment['ZETA_RUNTIME']

            $previousEap = $ErrorActionPreference
            try {
                # An interactive shell writes to stderr constantly (job control, prompts).
                # With EAP=Stop that becomes a terminating error, so native runs are isolated.
                $ErrorActionPreference = 'Continue'
                & $bash --rcfile $rcFile -i
            }
            finally {
                $ErrorActionPreference = $previousEap
                if ($null -eq $previous) { Remove-Item Env:\ZETA_BASH_CWD_FILE -ErrorAction SilentlyContinue }
                else { $env:ZETA_BASH_CWD_FILE = $previous }
                Remove-Item -LiteralPath (Split-Path -Parent $rcFile) -Recurse -Force -ErrorAction SilentlyContinue
            }

            if (Test-Path -LiteralPath $cwdFile) {
                try {
                    $recorded = (Get-Content -LiteralPath $cwdFile -Raw -ErrorAction Stop).Trim()
                    $target = ConvertFrom-ZetaPosixPath -Path $recorded
                    if ($target -and (Test-Path -LiteralPath $target)) { Set-Location -LiteralPath $target }
                }
                catch { }
                finally { Remove-Item -LiteralPath $cwdFile -Force -ErrorAction SilentlyContinue }
            }
        }

        'pwsh' {
            if (-not (Get-Command -Name 'pwsh' -ErrorAction SilentlyContinue)) { throw 'Zeta: pwsh not found.' }
            $previousEap = $ErrorActionPreference
            try { $ErrorActionPreference = 'Continue'; & pwsh -NoLogo } finally { $ErrorActionPreference = $previousEap }
        }

        'powershell' {
            $previousEap = $ErrorActionPreference
            try { $ErrorActionPreference = 'Continue'; & powershell -NoLogo } finally { $ErrorActionPreference = $previousEap }
        }
    }
}

function Get-ZetaShellTabArguments {
    <#
    .SYNOPSIS
        Build the wt.exe argument vector. Kept pure so it can be asserted without opening a window.
    #>
    param(
        [ValidateSet('bash', 'pwsh', 'powershell')]
        [string]$Name = 'bash',
        [string]$Path
    )

    if (-not $Path) { $Path = (Get-Location).Path }

    $arguments = @('-w', '0', 'new-tab', '-d', $Path)
    switch ($Name) {
        'bash' {
            $bash = Get-ZetaBashPath
            if (-not $bash) { throw 'Zeta: Git Bash not found. Install it with: winget install --id Git.Git' }
            $arguments += @('--title', 'Zeta Bash', $bash, '-li')
        }
        'pwsh' {
            $arguments += @('--title', 'Zeta PowerShell', 'pwsh.exe', '-NoLogo')
        }
        'powershell' {
            $arguments += @('--title', 'Zeta Windows PowerShell', 'powershell.exe', '-NoLogo')
        }
    }
    return , $arguments
}

function Open-ZetaShellTab {
    <#
    .SYNOPSIS
        Open a peer Windows Terminal tab at the same directory, so Ctrl+Tab jumps between shells.

    .EXAMPLE
        zeta shell tab bash

    .EXAMPLE
        Open-ZetaShellTab -Name pwsh -WhatIf
    #>
    [CmdletBinding(SupportsShouldProcess)]
    param(
        [ValidateSet('bash', 'pwsh', 'powershell')]
        [string]$Name = 'bash',
        [string]$Path
    )

    $wt = Get-Command -Name 'wt' -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1
    if (-not $wt) {
        throw 'Zeta: Windows Terminal (wt.exe) not found. Install it with: winget install --id Microsoft.WindowsTerminal'
    }

    $arguments = Get-ZetaShellTabArguments -Name $Name -Path $Path
    if (-not $PSCmdlet.ShouldProcess("Windows Terminal tab ($Name)", 'open')) { return $arguments }

    # Quote only what needs quoting; wt parses this as a normal command line.
    $quoted = ($arguments | ForEach-Object { if ($_ -match '\s') { '"' + $_ + '"' } else { $_ } }) -join ' '
    Start-Process -FilePath $wt.Source -ArgumentList $quoted
    return $arguments
}

function Get-ZetaShellSplitArguments {
    <#
    .SYNOPSIS
        Build the wt.exe split-pane argument vector (pure, so it can be asserted).
    .DESCRIPTION
        -V puts the new pane side by side (vertical divider), -H stacks it. Both panes start in
        the same directory, which is the whole point: same place, two shells, one window.
    #>
    param(
        [ValidateSet('bash', 'pwsh', 'powershell')]
        [string]$Name = 'bash',
        [string]$Path,
        [switch]$Horizontal
    )

    if (-not $Path) { $Path = (Get-Location).Path }

    $direction = '-V'
    if ($Horizontal) { $direction = '-H' }

    $arguments = @('-w', '0', 'split-pane', $direction, '-d', $Path)
    switch ($Name) {
        'bash' {
            $bash = Get-ZetaBashPath
            if (-not $bash) { throw 'Zeta: Git Bash not found. Install it with: winget install --id Git.Git' }
            $arguments += @('--title', 'Zeta Bash', $bash, '-li')
        }
        'pwsh' { $arguments += @('--title', 'Zeta PowerShell', 'pwsh.exe', '-NoLogo') }
        'powershell' { $arguments += @('--title', 'Zeta Windows PowerShell', 'powershell.exe', '-NoLogo') }
    }
    return , $arguments
}

function Open-ZetaShellSplit {
    <#
    .SYNOPSIS
        Split the current Windows Terminal window and open another shell in this directory.

    .EXAMPLE
        zeta shell split bash      # bash beside your PowerShell, same folder

    .EXAMPLE
        Open-ZetaShellSplit -Name pwsh -Horizontal
    #>
    [CmdletBinding(SupportsShouldProcess)]
    param(
        [ValidateSet('bash', 'pwsh', 'powershell')]
        [string]$Name = 'bash',
        [string]$Path,
        [switch]$Horizontal
    )

    $wt = Get-Command -Name 'wt' -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1
    if (-not $wt) {
        throw 'Zeta: Windows Terminal (wt.exe) not found. Install it with: winget install --id Microsoft.WindowsTerminal'
    }

    $arguments = Get-ZetaShellSplitArguments -Name $Name -Path $Path -Horizontal:$Horizontal
    if (-not $PSCmdlet.ShouldProcess("split pane ($Name)", 'open')) { return $arguments }

    if (-not $env:WT_SESSION) {
        throw 'Zeta: split needs Windows Terminal. Run this inside a Windows Terminal pane, or use: zeta shell tab bash'
    }

    $quoted = ($arguments | ForEach-Object { if ($_ -match '\s') { '"' + $_ + '"' } else { $_ } }) -join ' '
    Start-Process -FilePath $wt.Source -ArgumentList $quoted
    return $arguments
}

function Test-ZetaShellHandoff {
    <#
    .SYNOPSIS
        Check every link in the PowerShell -> bash -> PowerShell handoff and name the broken one.

    .DESCRIPTION
        The handoff has five moving parts: Git Bash, the bash runtime, the generated theme,
        the rcfile, and the cwd token written on exit. "It doesn't work" is useless; this says
        which link failed and what to do about it.
    #>
    [CmdletBinding()]
    param()

    $checks = New-Object System.Collections.ArrayList
    $add = {
        param($Check, $Status, $Detail, $Fix)
        [void]$checks.Add([pscustomobject]@{ Check = $Check; Status = $Status; Detail = $Detail; Fix = $Fix })
    }

    $bash = Get-ZetaBashPath
    if ($bash) { & $add 'Git Bash' 'ok' $bash '' }
    else { & $add 'Git Bash' 'fail' 'not found' 'winget install --id Git.Git' }

    $runtime = Join-Path (Join-Path $script:ModuleRoot 'Shell') 'zeta.bash'
    if (Test-Path -LiteralPath $runtime) { & $add 'Bash runtime' 'ok' $runtime '' }
    else { & $add 'Bash runtime' 'fail' 'missing from the module' 'Reinstall Zeta' }

    $themeFile = Get-ZetaBashThemePath
    if (Test-Path -LiteralPath $themeFile) {
        $age = [int]((Get-Date) - (Get-Item -LiteralPath $themeFile).LastWriteTime).TotalSeconds
        & $add 'Bash theme' 'ok' ('{0} ({1}s old)' -f $themeFile, $age) ''
    }
    else { & $add 'Bash theme' 'warn' 'not generated yet' 'Export-ZetaBashTheme' }

    if (-not $bash) { return $checks }

    $cwdFile = Join-Path $env:TEMP ('zeta-diag-' + [Guid]::NewGuid().ToString('N') + '.txt')
    $environment = Get-ZetaBashEnvironment -ThemePath $themeFile
    $rcFile = New-ZetaBashRcFile -TokenPosix (ConvertTo-ZetaPosixPath -Path $cwdFile) -Environment $environment -RuntimePosix $environment['ZETA_RUNTIME']

    try {
        & $bash -n (ConvertTo-ZetaPosixPath -Path $rcFile)
        if ($LASTEXITCODE -eq 0) { & $add 'rcfile syntax' 'ok' 'bash -n clean' '' }
        else { & $add 'rcfile syntax' 'fail' ('bash -n exit {0}' -f $LASTEXITCODE) 'Reinstall Zeta' }

        $previousEap = $ErrorActionPreference
        try {
            $ErrorActionPreference = 'Continue'
            & $bash --rcfile (ConvertTo-ZetaPosixPath -Path $rcFile) -i -c 'cd /c/Windows && exit 0' 2>&1 | Out-Null
        }
        finally { $ErrorActionPreference = $previousEap }

        if (Test-Path -LiteralPath $cwdFile) {
            $recorded = (Get-Content -LiteralPath $cwdFile -Raw -ErrorAction SilentlyContinue).Trim()
            $windowsPath = ConvertFrom-ZetaPosixPath -Path $recorded
            & $add 'cwd handoff' 'ok' ('bash reported {0} -> {1}' -f $recorded, $windowsPath) ''
        }
        else { & $add 'cwd handoff' 'fail' 'bash wrote no cwd file on exit' 'Run: zeta shell diagnose' }
    }
    finally {
        Remove-Item -LiteralPath $cwdFile -Force -ErrorAction SilentlyContinue
        Remove-Item -LiteralPath (Split-Path -Parent $rcFile) -Recurse -Force -ErrorAction SilentlyContinue
    }

    return $checks
}
