# Compile the active theme into a bash-sourceable file.
#
# One source of truth: theme JSON. PowerShell renders from it directly; bash gets a generated
# snapshot with pre-computed ANSI fragments, so the bash prompt needs no JSON parser and no
# colour maths at runtime. Regenerated on every theme change, which is what makes the look
# "live" in both shells.

function ConvertTo-ZetaBashSingleQuoted {
    param([AllowNull()][string]$Value)
    if ($null -eq $Value) { return "''" }
    return ("'" + ($Value -replace "'", "'\''") + "'")
}

function Get-ZetaBashThemePath {
    <#
    .SYNOPSIS
        Where the compiled bash theme lives. ZETA_BASH_THEME_FILE redirects it (tests).
    #>
    if ($env:ZETA_BASH_THEME_FILE) { return $env:ZETA_BASH_THEME_FILE }
    $homeDir = [Environment]::GetFolderPath('UserProfile')
    if (-not $homeDir) { $homeDir = $HOME }
    return (Join-Path (Join-Path $homeDir '.zeta') 'theme.bash')
}

function Get-ZetaBashAnsiLiteral {
    <#
    .SYNOPSIS
        #rrggbb -> a bash ANSI-C quoted string: $'\e[38;2;r;g;bm'
    #>
    param([string]$Hex, [switch]$Background, [string]$Mode = 'truecolor')

    if (-not $Hex -or $Mode -eq 'none') { return "`$''" }
    $rgb = ConvertFrom-ZetaHex $Hex
    if (-not $rgb) { return "`$''" }
    $prefix = 38
    if ($Background) { $prefix = 48 }
    return ("`$'\e[{0};2;{1};{2};{3}m'" -f $prefix, $rgb[0], $rgb[1], $rgb[2])
}

function Export-ZetaBashTheme {
    <#
    .SYNOPSIS
        Write the bash half of the theme: palette, glyphs, segment styles and ANSI fragments.

    .DESCRIPTION
        Produced from the same theme JSON and the same glyph-tier logic as the PowerShell
        prompt, so both shells agree on shape and colour. git-bash re-reads the file when its
        mtime changes, which is how a theme switch in either shell shows up in the other.

    .PARAMETER Path
        Output path. Defaults to ~/.zeta/theme.bash.

    .EXAMPLE
        Export-ZetaBashTheme

    .EXAMPLE
        Export-ZetaBashTheme -ThemeName nord
    #>
    [CmdletBinding()]
    param(
        [string]$ThemeName,
        [string]$Path
    )

    $config = Get-ZetaConfig
    if (-not $ThemeName) { $ThemeName = $config.theme }
    $theme = Import-ZetaTheme -Name $ThemeName
    $mode = Get-ZetaAnsiMode
    $tier = Get-ZetaGlyphTier
    # bash runs in a truecolor-capable terminal (Windows Terminal), so the generated file always
    # carries 24-bit sequences; only 'none' disables colour entirely.
    $bashMode = 'truecolor'
    if ($mode -eq 'none') { $bashMode = 'none' }

    if (-not $Path) {
        $Path = Get-ZetaBashThemePath
        $directory = Split-Path -Parent $Path
        if ($directory -and -not (Test-Path -LiteralPath $directory)) {
            New-Item -ItemType Directory -Path $directory -Force | Out-Null
        }
    }

    $text = Get-ZetaToneColor -Theme $theme -Tone 'text'
    $muted = Get-ZetaToneColor -Theme $theme -Tone 'muted'
    $accent = Get-ZetaToneColor -Theme $theme -Tone 'accent'
    $bg = Get-ZetaPaletteValue -Theme $theme -Key 'bg'

    $leftIds = @()
    foreach ($entry in @($theme.prompt.left)) {
        if ($entry -and $entry.segment) { $leftIds += [string]$entry.segment }
    }
    $rightIds = @()
    foreach ($entry in @($theme.prompt.right)) {
        if ($entry -and $entry.segment) { $rightIds += [string]$entry.segment }
    }

    $lines = New-Object System.Collections.Generic.List[string]
    $lines.Add('# generated by Zeta - do not edit; run: zeta theme set <name>')
    $lines.Add(('# theme: {0}   generated: {1}' -f $theme.name, (Get-Date).ToString('s')))
    $lines.Add('')
    $lines.Add(('ZETA_THEME={0}' -f (ConvertTo-ZetaBashSingleQuoted $theme.name)))
    $lines.Add(('ZETA_GLYPHS={0}' -f (ConvertTo-ZetaBashSingleQuoted $tier)))
    $lines.Add(('ZETA_COLOR={0}' -f (ConvertTo-ZetaBashSingleQuoted $bashMode)))
    $lines.Add(('ZETA_PALETTE_BG={0}' -f (ConvertTo-ZetaBashSingleQuoted $bg)))
    $lines.Add('')

    foreach ($glyph in @('corner', 'cornerEnd', 'dash', 'prompt', 'branch', 'ahead', 'behind', 'plus', 'modified', 'untracked', 'conflict', 'timer', 'folder', 'home')) {
        $name = 'ZETA_GLYPH_' + $glyph.ToUpperInvariant()
        $lines.Add(('{0}={1}' -f $name, (ConvertTo-ZetaBashSingleQuoted (Get-ZetaGlyph $glyph))))
    }
    $lines.Add('')

    # Reset must be a real escape even when no hex is involved.
    $resetLiteral = "`$'\e[0m'"
    if ($bashMode -eq 'none') { $resetLiteral = "`$''" }
    $lines.Add(('ZETA_ANSI_RESET={0}' -f $resetLiteral))
    $lines.Add(('ZETA_ANSI_TEXT={0}' -f (Get-ZetaBashAnsiLiteral -Hex $text -Mode $bashMode)))
    $lines.Add(('ZETA_ANSI_MUTED={0}' -f (Get-ZetaBashAnsiLiteral -Hex $muted -Mode $bashMode)))
    $lines.Add(('ZETA_ANSI_ACCENT={0}' -f (Get-ZetaBashAnsiLiteral -Hex $accent -Mode $bashMode)))
    $lines.Add('')

    $lines.Add(('ZETA_LEFT_SEGMENTS={0}' -f (ConvertTo-ZetaBashSingleQuoted ($leftIds -join ' '))))
    $lines.Add(('ZETA_RIGHT_SEGMENTS={0}' -f (ConvertTo-ZetaBashSingleQuoted ($rightIds -join ' '))))
    $lines.Add('')

    foreach ($entry in @($theme.prompt.left) + @($theme.prompt.right)) {
        if (-not $entry -or -not $entry.segment) { continue }
        $id = [string]$entry.segment
        $style = 'plain'
        if ($entry.ContainsKey('style') -and $entry.style) { $style = [string]$entry.style }
        $fgValue = $text
        if ($entry.ContainsKey('fg') -and $entry.fg) {
            $resolved = Resolve-ZetaColor -Value ([string]$entry.fg) -Theme $theme
            if ($resolved) { $fgValue = $resolved }
        }
        $bgValue = $null
        if ($entry.ContainsKey('bg') -and $entry.bg) { $bgValue = Resolve-ZetaColor -Value ([string]$entry.bg) -Theme $theme }

        $lines.Add(('ZETA_SEG_{0}_STYLE={1}' -f $id, (ConvertTo-ZetaBashSingleQuoted $style)))
        $lines.Add(('ZETA_SEG_{0}_FG={1}' -f $id, (Get-ZetaBashAnsiLiteral -Hex $fgValue -Mode $bashMode)))
        $lines.Add(('ZETA_SEG_{0}_BG={1}' -f $id, (Get-ZetaBashAnsiLiteral -Hex $bgValue -Background -Mode $bashMode)))
    }

    $content = ($lines -join "`n") + "`n"
    $temporary = "$Path.tmp"
    # UTF-8 without BOM: bash treats a BOM as part of the first token and errors on source.
    $encoding = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($temporary, $content, $encoding)
    Move-Item -LiteralPath $temporary -Destination $Path -Force
    return $Path
}
